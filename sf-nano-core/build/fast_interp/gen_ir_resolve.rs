/// Simple D-variant ops: IrOpKind name maps 1:1 to UPPER_SNAKE handler_lookup constant.
fn emit_simple_variant_ops(w: &mut CodeWriter) {
    w.line("// i32 binary");
    for op in I32_BINARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// i64 binary");
    for op in I64_BINARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f32 binary");
    for op in F32_BINARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f64 binary");
    for op in F64_BINARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// i32 comparisons");
    for op in I32_CMP_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// i64 comparisons");
    for op in I64_CMP_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f32 comparisons");
    for op in F32_CMP_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f64 comparisons");
    for op in F64_CMP_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// i32 unary");
    for op in I32_UNARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// i64 unary");
    for op in I64_UNARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f32 unary");
    for op in F32_UNARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// f64 unary");
    for op in F64_UNARY_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// Conversions");
    for op in CONVERSION_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// Sign extension");
    for op in SIGN_EXT_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// Saturating truncation");
    for op in SAT_TRUNC_OPS {
        wln!(w, "IrOpKind::{} => handler_lookup::{}[v],", op, to_upper_snake(op));
    }
    w.line("// Stack ops");
    w.line("IrOpKind::Drop => handler_lookup::DROP[v],");
    w.line("IrOpKind::Select => handler_lookup::SELECT[v],");
    w.blank();
}

/// Memory load/store handlers with fast (mem0) vs MM dispatch.
fn emit_memory_handlers(w: &mut CodeWriter) {
    w.line("// Memory loads — fast (mem0) vs MM (multi-memory)");
    for op in LOAD_OPS {
        let upper = to_upper_snake(op);
        wln!(w, "IrOpKind::{} {{ memidx: 0, .. }} => handler_lookup::{}[v],", op, upper);
        wln!(w, "IrOpKind::{} {{ .. }} => handler_lookup::{}_MM[v],", op, upper);
    }
    w.line("// Memory stores");
    for op in STORE_OPS {
        let upper = to_upper_snake(op);
        wln!(w, "IrOpKind::{} {{ memidx: 0, .. }} => handler_lookup::{}[v],", op, upper);
        wln!(w, "IrOpKind::{} {{ .. }} => handler_lookup::{}_MM[v],", op, upper);
    }
    w.blank();
}

/// Emit (0, 0, 0) match arms for ops with no immediates.
fn emit_raw_encode_arms(w: &mut CodeWriter) {
    w.line("// No immediates — zero encoding");

    // Collect all no-immediate ops into a big | pattern
    let mut ops: Vec<&str> = Vec::new();

    ops.extend_from_slice(I32_BINARY_OPS);
    ops.extend_from_slice(I64_BINARY_OPS);
    ops.extend_from_slice(F32_BINARY_OPS);
    ops.extend_from_slice(F64_BINARY_OPS);
    ops.extend_from_slice(I32_CMP_OPS);
    ops.extend_from_slice(I64_CMP_OPS);
    ops.extend_from_slice(F32_CMP_OPS);
    ops.extend_from_slice(F64_CMP_OPS);
    ops.extend_from_slice(I32_UNARY_OPS);
    ops.extend_from_slice(I64_UNARY_OPS);
    ops.extend_from_slice(F32_UNARY_OPS);
    ops.extend_from_slice(F64_UNARY_OPS);
    ops.extend_from_slice(CONVERSION_OPS);
    ops.extend_from_slice(SIGN_EXT_OPS);
    ops.extend_from_slice(SAT_TRUNC_OPS);

    // Emit in groups of 5 per line for readability
    let chunks: Vec<&[&str]> = ops.chunks(5).collect();
    for chunk in &chunks {
        let items: Vec<String> = chunk.iter().map(|op| format!("IrOpKind::{}", op)).collect();
        w.fmt(format_args!("{} |", items.join(" | ")));
    }
    // Structural and stack-only ops
    w.line("IrOpKind::RefNull | IrOpKind::RefIsNull |");
    w.line("IrOpKind::Drop | IrOpKind::Select |");
    w.line("IrOpKind::Block | IrOpKind::Loop | IrOpKind::End | IrOpKind::Nop |");
    w.line("IrOpKind::Unreachable | IrOpKind::Term => (0, 0, 0),");
    w.line("// Note: Fused and Data are handled separately above");
    w.blank();

}

// =============================================================================
// PascalCase → UPPER_SNAKE conversion
// =============================================================================

fn to_upper_snake(pascal: &str) -> String {
    let mut result = String::new();
    for (i, ch) in pascal.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            // Don't insert underscore between consecutive uppercase (e.g., "I32")
            let prev = pascal.chars().nth(i - 1).unwrap();
            if prev.is_lowercase() || prev.is_numeric() {
                result.push('_');
            } else if i + 1 < pascal.len() {
                let next = pascal.chars().nth(i + 1).unwrap();
                if next.is_lowercase() {
                    result.push('_');
                }
            }
        }
        result.push(ch.to_ascii_uppercase());
    }
    result
}

