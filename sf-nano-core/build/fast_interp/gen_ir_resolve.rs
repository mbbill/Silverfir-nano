//! Generate `resolve_handler` and `encode_operands` functions.
//!
//! These map IrOpKind directly to handler function pointers and encoded immediates,
//! replacing the intermediate ir_backend.rs + PatternData + finalize_pattern_data pipeline.

use std::fs;
use std::path::PathBuf;

use super::code_writer::CodeWriter;
use super::types::HandlersFile;

pub fn generate(_handlers: &HandlersFile, out_dir: &PathBuf) {
    let mut resolve_w = CodeWriter::new();
    let mut encode_w = CodeWriter::new();

    resolve_w.line("// Auto-generated by gen_ir_resolve.rs from handlers.toml");
    resolve_w.line("// DO NOT EDIT MANUALLY");
    resolve_w.blank();

    generate_resolve_handler(&mut resolve_w);

    encode_w.line("// Auto-generated by gen_ir_resolve.rs from handlers.toml");
    encode_w.line("// DO NOT EDIT MANUALLY");
    encode_w.blank();
    generate_encode_operands(&mut encode_w);

    let resolve_path = out_dir.join("fast_ir_resolve.rs");
    fs::write(&resolve_path, resolve_w.finish()).expect("Failed to write fast_ir_resolve.rs");

    let encode_path = out_dir.join("fast_operand_encoding.rs");
    fs::write(&encode_path, encode_w.finish()).expect("Failed to write fast_operand_encoding.rs");
}

// =============================================================================
// resolve_handler: IrOpKind + variant → Handler
// =============================================================================

fn generate_resolve_handler(w: &mut CodeWriter) {
    w.line("/// Map IrOpKind + variant to the correct handler function pointer.");
    w.line("///");
    w.line("/// Auto-generated from handlers.toml. Replaces ir_backend's handler selection.");
    w.line("#[inline]");
    w.line("pub fn resolve_handler(kind: &IrOpKind, variant: u8) -> Handler {");
    w.indent();
    w.line("let v = if variant > 0 { (variant - 1) as usize } else { 0 };");
    w.line("match kind {");
    w.indent();

    // Simple D-variant ops with no immediates (raw encoding)
    emit_simple_variant_ops(w);

    // Constants
    w.line("// Constants");
    w.line("IrOpKind::I32Const { .. } => handler_lookup::I32_CONST[v],");
    w.line("IrOpKind::I64Const { .. } => handler_lookup::I64_CONST[v],");
    w.line("IrOpKind::F32Const { .. } => handler_lookup::F32_CONST[v],");
    w.line("IrOpKind::F64Const { .. } => handler_lookup::F64_CONST[v],");
    w.blank();

    // Hot locals — register-indexed
    w.line("// Hot locals");
    w.line("IrOpKind::LocalGetHot { reg: 0 } => handler_lookup::LOCAL_GET_L0[v],");
    w.line("IrOpKind::LocalGetHot { reg: 1 } => handler_lookup::LOCAL_GET_L1[v],");
    w.line("IrOpKind::LocalGetHot { .. } => handler_lookup::LOCAL_GET_L2[v],");
    w.line("IrOpKind::LocalSetHot { reg: 0 } => handler_lookup::LOCAL_SET_L0[v],");
    w.line("IrOpKind::LocalSetHot { reg: 1 } => handler_lookup::LOCAL_SET_L1[v],");
    w.line("IrOpKind::LocalSetHot { .. } => handler_lookup::LOCAL_SET_L2[v],");
    w.line("IrOpKind::LocalTeeHot { reg: 0 } => handler_lookup::LOCAL_TEE_L0[v],");
    w.line("IrOpKind::LocalTeeHot { reg: 1 } => handler_lookup::LOCAL_TEE_L1[v],");
    w.line("IrOpKind::LocalTeeHot { .. } => handler_lookup::LOCAL_TEE_L2[v],");
    w.blank();

    // Frame locals
    w.line("// Frame locals");
    w.line("IrOpKind::LocalGetFrame { .. } => handler_lookup::LOCAL_GET[v],");
    w.line("IrOpKind::LocalSetFrame { .. } => handler_lookup::LOCAL_SET[v],");
    w.line("IrOpKind::LocalTeeFrame { .. } => handler_lookup::LOCAL_TEE[v],");
    w.blank();

    // Spill/Fill — count-indexed
    w.line("// Spill/Fill");
    w.line("IrOpKind::Spill { count: 1, .. } => handler_lookup::SPILL_1[v],");
    w.line("IrOpKind::Spill { count: 2, .. } => handler_lookup::SPILL_2[v],");
    w.line("IrOpKind::Spill { count: 3, .. } => handler_lookup::SPILL_3[v],");
    w.line("IrOpKind::Spill { .. } => handler_lookup::SPILL_4[v],");
    w.line("IrOpKind::Fill { count: 1, .. } => handler_lookup::FILL_1[v],");
    w.line("IrOpKind::Fill { count: 2, .. } => handler_lookup::FILL_2[v],");
    w.line("IrOpKind::Fill { count: 3, .. } => handler_lookup::FILL_3[v],");
    w.line("IrOpKind::Fill { .. } => handler_lookup::FILL_4[v],");
    w.blank();

    // Memory loads — fast (mem0) vs MM (multi-memory)
    emit_memory_handlers(w);

    // Globals
    w.line("// Globals");
    w.line("IrOpKind::GlobalGet { .. } => handler_lookup::GLOBAL_GET[v],");
    w.line("IrOpKind::GlobalSet { .. } => handler_lookup::GLOBAL_SET[v],");
    w.blank();

    // Memory size/grow
    w.line("// Memory size/grow");
    w.line("IrOpKind::MemorySize { .. } => handler_lookup::MEMORY_SIZE[v],");
    w.line("IrOpKind::MemoryGrow { .. } => handler_lookup::MEMORY_GROW[v],");
    w.blank();

    // Bulk memory ternary
    w.line("// Bulk memory");
    w.line("IrOpKind::MemoryFill { .. } => handler_lookup::MEMORY_FILL[v],");
    w.line("IrOpKind::MemoryCopy { .. } => handler_lookup::MEMORY_COPY[v],");
    w.line("IrOpKind::MemoryInit { .. } => handler_lookup::MEMORY_INIT[v],");
    w.line("IrOpKind::DataDrop { .. } => op_data_drop as Handler,");
    w.blank();

    // Tables
    w.line("// Tables");
    w.line("IrOpKind::TableGet { .. } => handler_lookup::TABLE_GET[v],");
    w.line("IrOpKind::TableSet { .. } => handler_lookup::TABLE_SET[v],");
    w.line("IrOpKind::TableSize { .. } => handler_lookup::TABLE_SIZE[v],");
    w.line("IrOpKind::TableGrow { .. } => handler_lookup::TABLE_GROW[v],");
    w.line("IrOpKind::TableFill { .. } => handler_lookup::TABLE_FILL[v],");
    w.line("IrOpKind::TableCopy { .. } => handler_lookup::TABLE_COPY[v],");
    w.line("IrOpKind::TableInit { .. } => handler_lookup::TABLE_INIT[v],");
    w.line("IrOpKind::ElemDrop { .. } => op_elem_drop as Handler,");
    w.blank();

    // References
    w.line("// References");
    w.line("IrOpKind::RefNull => handler_lookup::REF_NULL[v],");
    w.line("IrOpKind::RefIsNull => handler_lookup::REF_IS_NULL[v],");
    w.line("IrOpKind::RefFunc { .. } => handler_lookup::REF_FUNC[v],");
    w.blank();

    // Control flow — D-variant
    w.line("// Control flow — variant");
    w.line("IrOpKind::If => handler_lookup::IF_[v],");
    w.line("IrOpKind::BrIfSimple => handler_lookup::BR_IF_SIMPLE[v],");
    w.line("IrOpKind::BrIf { .. } => handler_lookup::BR_IF[v],");
    w.line("IrOpKind::BrTable { .. } => handler_lookup::BR_TABLE[v],");
    w.blank();

    // Control flow — direct (no variant)
    w.line("// Control flow — direct");
    w.line("IrOpKind::Block => op_block as Handler,");
    w.line("IrOpKind::Loop => op_loop as Handler,");
    w.line("IrOpKind::End => op_end as Handler,");
    w.line("IrOpKind::Nop => op_nop as Handler,");
    w.line("IrOpKind::Else => op_else_ as Handler,");
    w.line("IrOpKind::Br { .. } => op_br as Handler,");
    w.blank();

    // Calls — direct
    w.line("// Calls");
    w.line("IrOpKind::CallExternal { .. } => op_call_external as Handler,");
    w.line("IrOpKind::CallInternal { .. } => op_call_internal as Handler,");
    w.line("IrOpKind::CallIndirect { .. } => op_call_indirect as Handler,");
    w.blank();

    // Returns — direct
    w.line("// Returns");
    w.line("IrOpKind::ReturnVoid { .. } => op_return_void as Handler,");
    w.line("IrOpKind::ReturnOne { .. } => op_return_one as Handler,");
    w.line("IrOpKind::Return { .. } => op_return as Handler,");
    w.line("IrOpKind::Unreachable => op_unreachable as Handler,");
    w.blank();

    // Prologue / terminal
    w.line("// Prologue / terminal / fused");
    w.line("IrOpKind::InitLocals { .. } => op_init_locals as Handler,");
    w.line("IrOpKind::Term => op_term as Handler,");
    w.line("IrOpKind::Data { .. } => op_data as Handler,");
    w.line("IrOpKind::Fused { .. } => op_nop as Handler, // handler comes from ResolvedInst");
    w.blank();

    w.dedent();
    w.line("}");
    w.dedent();
    w.line("}");
}

// =============================================================================
// encode_operands: IrOpKind + target_ptr + fix_slot → (imm0, imm1, imm2)
// =============================================================================

fn generate_encode_operands(w: &mut CodeWriter) {
    w.line("/// Encode IrOpKind operands into (imm0, imm1, imm2).");
    w.line("///");
    w.line("/// Auto-generated. Replaces PatternData + finalize_pattern_data.");
    w.line("/// `target_ptr` is the resolved branch target pointer (0 on first pass).");
    w.line("/// `fix_slot` resolves logical slot references to final frame offsets.");
    w.line("#[inline]");
    w.line("pub fn encode_operands<F: Fn(SlotRef) -> u16>(");
    w.line("    kind: &IrOpKind,");
    w.line("    target_ptr: u64,");
    w.line("    fix_slot: &F,");
    w.line(") -> (u64, u64, u64) {");
    w.indent();
    w.line("match kind {");
    w.indent();

    // No-immediate ops → (0, 0, 0)
    emit_raw_encode_arms(w);

    // Constants
    w.line("// Constants");
    w.line("IrOpKind::I32Const { value } => encoding::r#const::encode(*value as u64),");
    w.line("IrOpKind::I64Const { value } => encoding::r#const::encode(*value),");
    w.line("IrOpKind::F32Const { value } => encoding::r#const::encode(*value as u64),");
    w.line("IrOpKind::F64Const { value } => encoding::r#const::encode(*value),");
    w.blank();

    // Locals
    w.line("// Hot locals (idx = 0 for register-cached locals)");
    w.line("IrOpKind::LocalGetHot { .. } => encoding::local_get::encode(0),");
    w.line("IrOpKind::LocalSetHot { .. } => encoding::local_set::encode(0),");
    w.line("IrOpKind::LocalTeeHot { .. } => encoding::local_tee::encode(0),");
    w.line("// Frame locals already carry absolute frame slots");
    w.line("IrOpKind::LocalGetFrame { idx } => encoding::local_get::encode(*idx),");
    w.line("IrOpKind::LocalSetFrame { idx } => encoding::local_set::encode(*idx),");
    w.line("IrOpKind::LocalTeeFrame { idx } => encoding::local_tee::encode(*idx),");
    w.blank();

    // Spill/Fill
    w.line("// Spill/Fill (slots are absolute frame slots)");
    w.line("IrOpKind::Spill { slot, .. } => encoding::spill_1::encode(*slot),");
    w.line("IrOpKind::Fill { slot, .. } => encoding::fill_1::encode(*slot),");
    w.blank();

    // Memory loads/stores
    w.line("// Memory loads");
    for op in LOAD_OPS {
        wln!(w, "IrOpKind::{} {{ offset, memidx, .. }} => encoding::load::encode(*offset, *memidx),", op);
    }
    w.line("// Memory stores");
    for op in STORE_OPS {
        wln!(w, "IrOpKind::{} {{ offset, memidx, .. }} => encoding::store::encode(*offset, *memidx),", op);
    }
    w.blank();

    // Globals
    w.line("// Globals");
    w.line("IrOpKind::GlobalGet { idx } => encoding::global::encode(*idx as u64),");
    w.line("IrOpKind::GlobalSet { idx } => encoding::global::encode(*idx as u64),");
    w.blank();

    // Memory size/grow
    w.line("// Memory size/grow");
    w.line("IrOpKind::MemorySize { mem_idx } => encoding::memory_size::encode(*mem_idx as u64),");
    w.line("IrOpKind::MemoryGrow { mem_idx } => encoding::memory_grow::encode(*mem_idx as u64),");
    w.blank();

    // Bulk memory ternary
    w.line("// Bulk memory ternary");
    w.line("IrOpKind::MemoryFill { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::MemoryCopy { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::MemoryInit { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::DataDrop { data_idx } => encoding::drop_op::encode(*data_idx as u64),");
    w.blank();

    // Tables
    w.line("// Tables");
    w.line("IrOpKind::TableGet { table_idx } => encoding::table_get::encode(*table_idx as u64),");
    w.line("IrOpKind::TableSet { table_idx } => encoding::table_set::encode(*table_idx as u64),");
    w.line("IrOpKind::TableSize { table_idx } => encoding::table_size::encode(*table_idx as u64),");
    w.line("IrOpKind::TableGrow { table_idx } => encoding::table_grow::encode(*table_idx as u64),");
    w.line("IrOpKind::TableFill { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::TableCopy { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::TableInit { imm0, imm1 } => encoding::ternary::encode(*imm0 as u64, *imm1 as u64),");
    w.line("IrOpKind::ElemDrop { elem_idx } => encoding::drop_op::encode(*elem_idx as u64),");
    w.blank();

    // References
    w.line("// References");
    w.line("IrOpKind::RefFunc { func_idx } => encoding::ref_func::encode(*func_idx as u64),");
    w.blank();

    // Control flow with target
    w.line("// Control flow — target encoding");
    w.line("IrOpKind::If => encoding::if_::encode(target_ptr),");
    w.line("IrOpKind::Else => encoding::else_::encode(target_ptr),");
    w.line("IrOpKind::BrIfSimple => encoding::br_if_simple::encode(target_ptr),");
    w.line("IrOpKind::Br { stack_drop, arity, height, operand_base_offset } =>");
    w.line("    encoding::br::encode(target_ptr, *stack_drop as u64, *arity, *height, *operand_base_offset),");
    w.line("IrOpKind::BrIf { stack_drop, arity, height, operand_base_offset } =>");
    w.line("    encoding::br_if::encode(target_ptr, *stack_drop as u64, *arity, *height, *operand_base_offset),");
    w.line("IrOpKind::BrTable { entry_count, data_slot_count, height, operand_base_offset, .. } =>");
    w.line("    encoding::br_table::encode(*entry_count as u64, *data_slot_count as u64, *operand_base_offset, *height),");
    w.blank();

    // Calls
    w.line("// Calls");
    w.line("IrOpKind::CallExternal { func_idx, delta } =>");
    w.line("    encoding::call_external::encode(*func_idx as u64, fix_slot(*delta)),");
    w.line("IrOpKind::CallInternal { callee, delta } =>");
    w.line("    encoding::call_internal::encode(*callee, fix_slot(*delta)),");
    w.line("IrOpKind::CallIndirect { type_idx, table_idx, delta, operand_base_offset, height } =>");
    w.line("    encoding::call_indirect::encode(*type_idx as u64, *table_idx as u64, fix_slot(*delta), *operand_base_offset, *height),");
    w.blank();

    // Returns
    w.line("// Returns");
    w.line("IrOpKind::ReturnVoid { frame_size } => encoding::return_void::encode(*frame_size),");
    w.line("IrOpKind::ReturnOne { frame_size, operand_base_offset, height } =>");
    w.line("    encoding::return_one::encode(*frame_size, *operand_base_offset, *height),");
    w.line("IrOpKind::Return { arity, frame_size, operand_base_offset, height } =>");
    w.line("    encoding::r#return::encode(*arity, *frame_size, *operand_base_offset, *height),");
    w.blank();

    // Prologue
    w.line("// Prologue");
    w.line("IrOpKind::InitLocals { k0, k1, k2 } => encoding::init_locals::encode(*k0, *k1, *k2),");
    w.blank();

    // Data pseudo-instruction
    w.line("// Data pseudo-instruction");
    w.line("IrOpKind::Data { imm0, imm1, imm2 } => encoding::raw::encode(*imm0, *imm1, *imm2),");
    w.blank();

    // Fused (pre-encoded with target patching)
    w.line("// Fused (pre-encoded by fusion backend)");
    w.line("IrOpKind::Fused { imm0, imm1, imm2, target_imm } => match *target_imm {");
    w.line("    0 => (target_ptr, *imm1, *imm2),");
    w.line("    1 => (*imm0, target_ptr, *imm2),");
    w.line("    2 => (*imm0, *imm1, target_ptr),");
    w.line("    _ => (*imm0, *imm1, *imm2),");
    w.line("},");

    w.dedent();
    w.line("}");
    w.dedent();
    w.line("}");
}

