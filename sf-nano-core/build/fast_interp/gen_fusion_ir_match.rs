/// Map pattern op name to IrOpKind match pattern.
fn ir_kind_discriminant(op: &str) -> String {
    match op {
        "i32_const" => "IrOpKind::I32Const { .. }".to_string(),
        "i64_const" => "IrOpKind::I64Const { .. }".to_string(),
        "local_get" => "IrOpKind::LocalGetFrame { .. }".to_string(),
        "local_set" => "IrOpKind::LocalSetFrame { .. }".to_string(),
        "local_tee" => "IrOpKind::LocalTeeFrame { .. }".to_string(),
        "local_get_l0" => "IrOpKind::LocalGetHot { reg: 0 }".to_string(),
        "local_set_l0" => "IrOpKind::LocalSetHot { reg: 0 }".to_string(),
        "local_tee_l0" => "IrOpKind::LocalTeeHot { reg: 0 }".to_string(),
        "local_get_l1" => "IrOpKind::LocalGetHot { reg: 1 }".to_string(),
        "local_set_l1" => "IrOpKind::LocalSetHot { reg: 1 }".to_string(),
        "local_tee_l1" => "IrOpKind::LocalTeeHot { reg: 1 }".to_string(),
        "local_get_l2" => "IrOpKind::LocalGetHot { reg: 2 }".to_string(),
        "local_set_l2" => "IrOpKind::LocalSetHot { reg: 2 }".to_string(),
        "local_tee_l2" => "IrOpKind::LocalTeeHot { reg: 2 }".to_string(),
        "br_if" => "IrOpKind::BrIfSimple".to_string(),
        "if_" => "IrOpKind::If".to_string(),
        _ => {
            let name = to_pascal_case(op);
            // Memory ops have fields
            if op.contains("load") || op.contains("store") {
                format!("IrOpKind::{} {{ .. }}", name)
            } else {
                format!("IrOpKind::{}", name)
            }
        }
    }
}

/// Generate a boolean check for whether ir[pos+offset] matches pattern op.
fn ir_kind_check(op: &str, offset: usize) -> String {
    format!("matches!(&ir[pos+{}].kind, {})", offset, ir_kind_discriminant(op))
}

/// Generate code to extract a field value from an IrOpKind at position `from_idx`.
fn ir_field_extract(pattern_op: &str, field_name: &str, from_idx: usize) -> String {
    match pattern_op {
        "i32_const" => format!(
            "let {} = match &ir[pos+{}].kind {{ IrOpKind::I32Const {{ value }} => *value, _ => unreachable!() }}",
            field_name, from_idx
        ),
        "i64_const" => format!(
            "let {} = match &ir[pos+{}].kind {{ IrOpKind::I64Const {{ value }} => *value, _ => unreachable!() }}",
            field_name, from_idx
        ),
        "local_get" | "local_set" | "local_tee" => format!(
            "let {} = match &ir[pos+{}].kind {{ IrOpKind::LocalGetFrame {{ idx }} | IrOpKind::LocalSetFrame {{ idx }} | IrOpKind::LocalTeeFrame {{ idx }} => *idx as u32, _ => unreachable!() }}",
            field_name, from_idx
        ),
        op if op.contains("load") || op.contains("store") => {
            // Extract offset field from memory ops
            if field_name == "offset" || field_name.starts_with("offset") {
                let kind_name = to_pascal_case(op);
                format!(
                    "let {} = match &ir[pos+{}].kind {{ IrOpKind::{} {{ offset, .. }} => *offset, _ => unreachable!() }}",
                    field_name, from_idx, kind_name
                )
            } else {
                format!("let {} = 0u32 /* unknown field for {} */", field_name, op)
            }
        }
        _ => format!("let {} = 0u64 /* no extractable field for {} */", field_name, pattern_op),
    }
}

/// Build the encoding function call string.
/// For target-bearing patterns, pass 0u64 as the target placeholder
/// (the finalizer patches it later via encode_operands).
fn build_encode_call(f: &FusedHandler, fields: &[Field]) -> String {
    let escaped_name = escape_rust_keyword(&f.op);

    // Build args in field order, including target fields (as 0u64 placeholder)
    let args: Vec<String> = fields.iter().map(|field| {
        if field.kind == FieldKind::Target {
            "0u64".to_string()
        } else {
            match field.bits {
                8 => format!("{} as u8", field.name),
                16 => format!("{} as u16", field.name),
                32 => format!("{} as u32", field.name),
                64 => format!("{} as u64", field.name),
                _ => field.name.clone(),
            }
        }
    }).collect();

    if args.is_empty() {
        format!("encoding::{}::encode()", escaped_name)
    } else {
        format!("encoding::{}::encode({})", escaped_name, args.join(", "))
    }
}

/// Compute which imm slot the target field occupies (same layout as gen_encoding.rs).
fn compute_target_imm_slot(fields: &[Field]) -> u8 {
    let mut current_imm = 0u8;
    let mut current_bit = 0u32;

    for field in fields {
        if current_bit + field.bits > 64 {
            current_imm += 1;
            current_bit = 0;
        }
        if field.kind == FieldKind::Target {
            return current_imm;
        }
        current_bit += field.bits;
    }
    0xFF // no target field
}

/// Escape Rust keywords for module paths (e.g., "const" → "r#const").
fn escape_rust_keyword(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "const", "return", "type", "match", "loop", "move", "ref", "self", "super",
        "static", "unsafe", "where", "async", "await", "dyn", "abstract", "become",
        "box", "do", "final", "macro", "override", "priv", "try", "typeof", "unsized",
        "virtual", "yield", "fn", "let", "mut", "pub", "struct", "enum", "trait", "impl",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{}", name)
    } else {
        name.to_string()
    }
}
