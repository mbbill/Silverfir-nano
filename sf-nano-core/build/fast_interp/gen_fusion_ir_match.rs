//! Generate IR-level fusion pattern matching.
//!
//! Produces `fast_fusion_ir_match.rs`: a `try_fuse()` function that
//! matches `IrOpKind` sequences and returns pre-encoded fused instruction data.

use super::op_classify::{
    get_pop_push, has_branch, has_if, is_comparison_op, is_tos_none, CategoryMap,
};
use super::types::{to_pascal_case, Field, FieldKind, FusedHandler};

/// Generate the IR-level fusion matching file.
pub fn generate(fused_handlers: &[FusedHandler], categories: &CategoryMap) -> String {
    let mut code = String::new();

    code.push_str("// Auto-generated by gen_fusion_ir_match.rs from handlers_fused.toml\n");
    code.push_str("// DO NOT EDIT MANUALLY\n");
    code.push_str("// All imports are provided by the including module (fusion.rs).\n\n");

    // Generate per-pattern try_fuse_* functions
    for f in fused_handlers {
        generate_try_fuse_one(&mut code, f, categories);
    }

    // Generate main dispatcher
    generate_dispatcher(&mut code, fused_handlers, categories);

    code
}

/// Generate empty stub when no fused entries exist.
pub fn generate_empty() -> String {
    let mut code = String::new();
    code.push_str("// Auto-generated — no fused patterns\n\n");
    code.push_str("// All imports provided by the including module.\n\n");
    code.push_str("#[allow(unused)]\n");
    code.push_str("pub fn try_fuse(_ir: &[IrOp], _pos: usize) -> Option<(usize, Handler, IrOpKind, Option<usize>, bool)> {\n");
    code.push_str("    None\n");
    code.push_str("}\n");
    code
}

// =============================================================================
// Per-pattern function generation
// =============================================================================

fn generate_try_fuse_one(code: &mut String, f: &FusedHandler, _categories: &CategoryMap) {
    let n = f.pattern.len();
    let fields = f.get_fields();
    let is_br = has_branch(f);
    let is_if_pat = has_if(f);
    let tos_none = is_tos_none(f);
    let target_imm = compute_target_imm_slot(fields);
    let upper_name = f.op.to_uppercase();

    code.push_str(&format!("/// Pattern: {}\n", f.pattern.join(" → ")));
    code.push_str(&format!(
        "#[inline]\nfn try_fuse_{}(ir: &[IrOp], pos: usize) -> Option<(usize, Handler, IrOpKind, Option<usize>, bool)> {{\n",
        f.op
    ));

    // Check remaining length
    code.push_str(&format!("    if ir.len() - pos < {} {{ return None; }}\n", n));

    // Check each pattern position matches the expected IrOpKind
    for i in 0..n {
        let pat_op = &f.pattern[i];
        let check = ir_kind_check(pat_op, i);
        code.push_str(&format!("    if !{} {{ return None; }}\n", check));
    }

    // For br_if patterns: check that the br_if is simple (has alt_target)
    if is_br {
        let br_idx = f.pattern.iter().position(|op| op == "br_if").unwrap();
        code.push_str(&format!(
            "    if ir[pos+{}].alt_target.is_none() {{ return None; }}\n", br_idx
        ));
        // Check the height is sufficient for br_if_simple (pre_height >= 1)
        code.push_str(&format!(
            "    if ir[pos+{}].pre_height < 1 {{ return None; }}\n", br_idx
        ));
    }

    // For if_ patterns: we only fuse simple if (no block params/results)
    // The IR doesn't track block types, so we trust the lowering.
    // However, the if_ in IR always has has_target=true. Fine.

    // Branch-aware yielding: non-branch patterns ending with comparison
    // should yield if next op is br_if or if_ (prefer branch fusion)
    if !is_br && !is_if_pat {
        let last_op = f.pattern.last().unwrap();
        if is_comparison_op(last_op) {
            code.push_str(&format!(
                "    if pos + {} < ir.len() && matches!(&ir[pos+{}].kind, IrOpKind::BrIfSimple | IrOpKind::If) {{ return None; }}\n",
                n, n
            ));
        }
    }

    // Extract field values from IrOpKind variants
    for field in fields {
        if field.kind == FieldKind::Target {
            continue; // target is from alt_target, not from kind fields
        }
        let from_idx = field.from.expect(&format!(
            "Field '{}' in '{}' missing 'from'", field.name, f.op
        ));
        let extract = ir_field_extract(&f.pattern[from_idx], &field.name, from_idx);
        code.push_str(&format!("    {};\n", extract));
    }

    // Compute handler
    if tos_none {
        // Single handler, no variants
        code.push_str(&format!(
            "    let handler: Handler = full_set::op_{} as Handler;\n", f.op
        ));
    } else {
        // Compute D-variant from pre_height and the fused pattern's net push.
        // The wrapper's get_register_args_for_pattern positions are based on:
        //   - pop >= push: input stack (reference depth = h)
        //   - push > pop:  output stack (reference depth = h + push - pop)
        // Unified: ref_depth = h + max(0, push - pop)
        let (pop, push) = get_pop_push(f);
        let net_push = push.saturating_sub(pop) as usize;
        code.push_str(&format!(
            "    let ref_depth = ir[pos].pre_height as usize + {};\n", net_push
        ));
        code.push_str("    let variant_idx = if ref_depth == 0 { 0 } else { (ref_depth - 1) % 4 };\n");
        code.push_str(&format!(
            "    let handler: Handler = handler_lookup::{}[variant_idx];\n", upper_name
        ));
    }

    // Compute encoding
    let encode_call = build_encode_call(f, fields);
    code.push_str(&format!("    let (imm0, imm1, imm2) = {};\n", encode_call));

    // Build return value
    if is_br {
        let br_idx = f.pattern.iter().position(|op| op == "br_if").unwrap();
        code.push_str(&format!(
            "    let alt = ir[pos+{}].alt_target;\n", br_idx
        ));
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: {} }}, alt, true))\n",
            n, target_imm
        ));
    } else if is_if_pat {
        let if_idx = f.pattern.iter().position(|op| op == "if_").unwrap();
        code.push_str(&format!(
            "    let alt = ir[pos+{}].alt_target;\n", if_idx
        ));
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: {} }}, alt, true))\n",
            n, target_imm
        ));
    } else {
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: 0xFF }}, None, false))\n",
            n
        ));
    }

    code.push_str("}\n\n");
}

// =============================================================================
// Dispatcher generation
// =============================================================================

fn generate_dispatcher(code: &mut String, fused: &[FusedHandler], categories: &CategoryMap) {
    // Group by first op discriminant
    let mut by_first: Vec<(String, Vec<&FusedHandler>)> = Vec::new();
    for f in fused {
        let disc = ir_kind_discriminant(&f.pattern[0]);
        if let Some(entry) = by_first.iter_mut().find(|(d, _)| *d == disc) {
            entry.1.push(f);
        } else {
            by_first.push((disc, vec![f]));
        }
    }
    // Sort groups: longest patterns first within each group
    for (_, group) in &mut by_first {
        group.sort_by(|a, b| b.pattern.len().cmp(&a.pattern.len()));
    }
    by_first.sort_by(|a, b| a.0.cmp(&b.0));

    code.push_str("/// Try to fuse a pattern starting at `pos` in the IR.\n");
    code.push_str("///\n");
    code.push_str("/// Returns `(len, handler, kind, alt_target, has_target)` on match.\n");
    code.push_str("#[allow(unused_variables)]\n");
    code.push_str("pub fn try_fuse(ir: &[IrOp], pos: usize) -> Option<(usize, Handler, IrOpKind, Option<usize>, bool)> {\n");
    code.push_str("    match &ir[pos].kind {\n");

    for (disc, group) in &by_first {
        code.push_str(&format!("        {} => {{\n", disc));
        for f in group {
            code.push_str(&format!(
                "            if let Some(r) = try_fuse_{}(ir, pos) {{ return Some(r); }}\n",
                f.op
            ));
        }
        code.push_str("        }\n");
    }

    code.push_str("        _ => {}\n");
    code.push_str("    }\n");
    code.push_str("    None\n");
    code.push_str("}\n");
}

