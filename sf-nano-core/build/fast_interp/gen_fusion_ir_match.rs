//! Generate IR-level fusion pattern matching (variant-qualified).
//!
//! Produces `fast_fusion_ir_match.rs`: a `try_fuse()` function that
//! matches `IrOpKind` sequences with variant checks, returning pre-encoded
//! fused instruction data with a single handler (no D1-D4 lookup).

use super::op_classify::{
    has_branch, has_if, is_comparison_op, parse_variant_qualified, strip_variant_suffix,
    CategoryMap,
};
use super::types::{to_pascal_case, Field, FieldKind, FusedHandler};

/// Generate the IR-level fusion matching file.
pub fn generate(fused_handlers: &[FusedHandler], _categories: &CategoryMap) -> String {
    let mut code = String::new();

    code.push_str("// Auto-generated by gen_fusion_ir_match.rs from handlers_fused.toml\n");
    code.push_str("// DO NOT EDIT MANUALLY\n");
    code.push_str(
        "// Variant-qualified fusion: matches IrOpKind + variant, single handler per entry\n",
    );
    code.push_str("// All imports are provided by the including module (fusion.rs).\n\n");

    // Generate per-pattern try_fuse_* functions
    for f in fused_handlers {
        generate_try_fuse_one(&mut code, f);
    }

    // Generate main dispatcher
    generate_dispatcher(&mut code, fused_handlers);

    code
}

/// Generate empty stub when no fused entries exist.
pub fn generate_empty() -> String {
    let mut code = String::new();
    code.push_str("// Auto-generated — no fused patterns\n\n");
    code.push_str("// All imports provided by the including module.\n\n");
    code.push_str("#[allow(unused)]\n");
    code.push_str("pub fn try_fuse(_ir: &[IrOp], _pos: usize) -> Option<(usize, Handler, IrOpKind, Option<OpIndex>, bool)> {\n");
    code.push_str("    None\n");
    code.push_str("}\n");
    code
}

// =============================================================================
// Per-pattern function generation
// =============================================================================

fn generate_try_fuse_one(code: &mut String, f: &FusedHandler) {
    let n = f.pattern.len();
    let fields = f.get_fields();
    let is_br = has_branch(f);
    let is_if_pat = has_if(f);
    let target_imm = compute_target_imm_slot(fields);

    // Parse all pattern elements
    let parsed: Vec<(&str, u8)> = f
        .pattern
        .iter()
        .map(|p| parse_variant_qualified(p))
        .collect();

    code.push_str(&format!("/// Pattern: {}\n", f.pattern.join(" → ")));
    code.push_str(&format!(
        "#[inline]\nfn try_fuse_{}(ir: &[IrOp], pos: usize) -> Option<(usize, Handler, IrOpKind, Option<OpIndex>, bool)> {{\n",
        f.op
    ));

    // Check remaining length
    code.push_str(&format!(
        "    if ir.len() - pos < {} {{ return None; }}\n",
        n
    ));

    // Check each pattern position: IrOpKind match AND variant match
    for i in 0..n {
        let (base_op, variant) = parsed[i];
        let check = ir_kind_check(base_op, i);
        code.push_str(&format!("    if !{} {{ return None; }}\n", check));
        code.push_str(&format!(
            "    if ir[pos+{}].variant != {} {{ return None; }}\n",
            i, variant
        ));
    }

    // For br_if patterns: check that the br_if is simple (has alt_target)
    if is_br {
        let br_idx = f
            .pattern
            .iter()
            .position(|op| strip_variant_suffix(op) == "br_if")
            .unwrap();
        code.push_str(&format!(
            "    if ir[pos+{}].alt_target.is_none() {{ return None; }}\n",
            br_idx
        ));
        code.push_str(&format!(
            "    if ir[pos+{}].pre_height < 1 {{ return None; }}\n",
            br_idx
        ));
    }

    // Branch-aware yielding: non-branch patterns ending with comparison
    // should yield if next op is br_if or if_ (prefer branch fusion)
    if !is_br && !is_if_pat {
        let last_op = f.pattern.last().unwrap();
        let (last_base, _) = parse_variant_qualified(last_op);
        if is_comparison_op(last_base) {
            code.push_str(&format!(
                "    if pos + {} < ir.len() && matches!(&ir[pos+{}].kind, IrOpKind::BrIfSimple | IrOpKind::If) {{ return None; }}\n",
                n, n
            ));
        }
    }

    // Extract field values from IrOpKind variants
    for field in fields {
        if field.kind == FieldKind::Target {
            continue; // target is from alt_target, not from kind fields
        }
        let from_idx = field
            .from
            .unwrap_or_else(|| panic!("Field '{}' in '{}' missing 'from'", field.name, f.op));
        let (base_op, _) = parsed[from_idx];
        let extract = ir_field_extract(base_op, &field.name, from_idx);
        code.push_str(&format!("    {};\n", extract));
    }

    // Single handler — no variant lookup needed
    code.push_str(&format!(
        "    let handler: Handler = full_set::op_{} as Handler;\n",
        f.op
    ));

    // Compute encoding
    let encode_call = build_encode_call(f, fields);
    code.push_str(&format!("    let (imm0, imm1, imm2) = {};\n", encode_call));

    // Build return value
    if is_br {
        let br_idx = f
            .pattern
            .iter()
            .position(|op| strip_variant_suffix(op) == "br_if")
            .unwrap();
        code.push_str(&format!("    let alt = ir[pos+{}].alt_target;\n", br_idx));
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: {} }}, alt, true))\n",
            n, target_imm
        ));
    } else if is_if_pat {
        let if_idx = f
            .pattern
            .iter()
            .position(|op| strip_variant_suffix(op) == "if_")
            .unwrap();
        code.push_str(&format!("    let alt = ir[pos+{}].alt_target;\n", if_idx));
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: {} }}, alt, true))\n",
            n, target_imm
        ));
    } else {
        code.push_str(&format!(
            "    Some(({}, handler, IrOpKind::Fused {{ imm0, imm1, imm2, target_imm: 0xFF }}, None, false))\n",
            n
        ));
    }

    code.push_str("}\n\n");
}

// =============================================================================
// Dispatcher generation
// =============================================================================

fn generate_dispatcher(code: &mut String, fused: &[FusedHandler]) {
    // Group by first op's IrOpKind discriminant (base op, ignoring variant)
    let mut by_first: Vec<(String, Vec<&FusedHandler>)> = Vec::new();
    for f in fused {
        let (base_op, _) = parse_variant_qualified(&f.pattern[0]);
        let disc = ir_kind_discriminant(base_op);
        if let Some(entry) = by_first.iter_mut().find(|(d, _)| *d == disc) {
            entry.1.push(f);
        } else {
            by_first.push((disc, vec![f]));
        }
    }
    // Sort groups: longest patterns first within each group
    for (_, group) in &mut by_first {
        group.sort_by(|a, b| b.pattern.len().cmp(&a.pattern.len()));
    }
    by_first.sort_by(|a, b| a.0.cmp(&b.0));

    code.push_str("/// Try to fuse a pattern starting at `pos` in the IR.\n");
    code.push_str("///\n");
    code.push_str("/// Returns `(len, handler, kind, alt_target, has_target)` on match.\n");
    code.push_str("#[allow(unused_variables)]\n");
    code.push_str("pub fn try_fuse(ir: &[IrOp], pos: usize) -> Option<(usize, Handler, IrOpKind, Option<OpIndex>, bool)> {\n");
    code.push_str("    match &ir[pos].kind {\n");

    for (disc, group) in &by_first {
        code.push_str(&format!("        {} => {{\n", disc));
        for f in group {
            code.push_str(&format!(
                "            if let Some(r) = try_fuse_{}(ir, pos) {{ return Some(r); }}\n",
                f.op
            ));
        }
        code.push_str("        }\n");
    }

    code.push_str("        _ => {}\n");
    code.push_str("    }\n");
    code.push_str("    None\n");
    code.push_str("}\n");
}

