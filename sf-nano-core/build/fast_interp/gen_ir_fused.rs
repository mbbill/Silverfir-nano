//! Generate `FusedIrOp` enum and `fused_stack_effect()` from handlers_fused.toml.
//!
//! Produces `fast_ir_fused_kinds.rs` which is include!()'d into ir.rs under cfg(fusion).

use std::fs;
use std::path::PathBuf;

use super::op_classify::{get_pop_push, has_branch_or_if, is_tos_none};
use super::types::{bits_to_rust_type, to_pascal_case, FieldKind, FusedHandler, HandlersFile};

pub fn generate(handlers: &HandlersFile, out_dir: &PathBuf) {
    let fused = &handlers.fused;
    let mut code = String::new();

    code.push_str("// Auto-generated by gen_ir_fused.rs from handlers_fused.toml\n");
    code.push_str("// DO NOT EDIT MANUALLY\n\n");

    generate_fused_enum(&mut code, fused);
    code.push('\n');
    generate_fused_stack_effect(&mut code, fused);
    code.push('\n');
    generate_fused_has_target(&mut code, fused);

    let out_path = out_dir.join("fast_ir_fused_kinds.rs");
    fs::write(&out_path, code).expect("Failed to write fast_ir_fused_kinds.rs");
}

fn generate_fused_enum(code: &mut String, fused: &[FusedHandler]) {
    code.push_str("/// Fused instruction variants from handlers_fused.toml.\n");
    code.push_str("#[derive(Debug, Clone)]\n");
    code.push_str("pub enum FusedIrOp {\n");

    for f in fused {
        let variant = to_pascal_case(&f.op);
        let fields = f.get_fields();

        // Collect non-target fields
        let non_target_fields: Vec<_> = fields
            .iter()
            .filter(|field| field.kind != FieldKind::Target)
            .collect();

        code.push_str(&format!("    /// Pattern: {}\n", f.pattern.join(" → ")));
        if non_target_fields.is_empty() {
            code.push_str(&format!("    {},\n", variant));
        } else {
            code.push_str(&format!("    {} {{\n", variant));
            for field in &non_target_fields {
                let rust_type = bits_to_rust_type(field.bits);
                code.push_str(&format!("        {}: {},\n", field.name, rust_type));
            }
            code.push_str("    },\n");
        }
    }

    code.push_str("}\n");
}

fn generate_fused_stack_effect(code: &mut String, fused: &[FusedHandler]) {
    code.push_str("/// Stack effect for fused ops: (pops, pushes).\n");
    code.push_str("#[inline]\n");
    code.push_str("pub fn fused_stack_effect(kind: &FusedIrOp) -> (u8, u8) {\n");
    code.push_str("    match kind {\n");

    for f in fused {
        let variant = to_pascal_case(&f.op);
        if is_tos_none(f) {
            code.push_str(&format!(
                "        FusedIrOp::{} {{ .. }} => (0, 0),\n",
                variant
            ));
        } else {
            let (pop, push) = get_pop_push(f);
            code.push_str(&format!(
                "        FusedIrOp::{} {{ .. }} => ({}, {}),\n",
                variant, pop, push
            ));
        }
    }

    code.push_str("    }\n");
    code.push_str("}\n");
}

fn generate_fused_has_target(code: &mut String, fused: &[FusedHandler]) {
    code.push_str("/// Whether a fused op has a branch target (br_if or if_ pattern).\n");
    code.push_str("#[inline]\n");
    code.push_str("pub fn fused_has_target(kind: &FusedIrOp) -> bool {\n");
    code.push_str("    match kind {\n");

    let has_any_target = fused.iter().any(|f| has_branch_or_if(f));

    if has_any_target {
        for f in fused {
            if has_branch_or_if(f) {
                let variant = to_pascal_case(&f.op);
                code.push_str(&format!(
                    "        FusedIrOp::{} {{ .. }} => true,\n",
                    variant
                ));
            }
        }
        code.push_str("        _ => false,\n");
    } else {
        code.push_str("        _ => false,\n");
    }

    code.push_str("    }\n");
    code.push_str("}\n");
}
